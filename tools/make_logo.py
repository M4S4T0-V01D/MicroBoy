#!/usr/bin/env python3
"""Generates the MicroBoy logo (Android adaptive icon layers + SVG) from one geometry.

Run from the repo root:  python3 tools/make_logo.py
"""
import os

RES = "app/src/main/res"
# Geometry in the 108x108 adaptive-icon viewport (safe zone: 66dp circle).
BODY = (38, 25, 32, 58, 7)          # x, y, w, h, corner radius
SCREEN = (42, 30, 24, 23, 2.5)
DPAD_C, ARM, LEN = (46.5, 66.5), 2.1, 6.0
BTN_A, BTN_B, BTN_R = (62.5, 63.5), (57.0, 68.5), 2.7
PILLS = [(48.5, 76.5, 5, 1.8), (55.5, 76.5, 5, 1.8)]
PX = 2.6                             # pixel size of the "M"
M = ["X...X", "XX.XX", "X.X.X", "X...X", "X...X"]

LAV, CORAL, MINT, INK, BG = "#B39DFF", "#FF8A80", "#7FE0C2", "#1E1B2E", "#14121F"


def rrect(x, y, w, h, r):
    return (f"M{x+r},{y} h{w-2*r} a{r},{r} 0 0 1 {r},{r} v{h-2*r} a{r},{r} 0 0 1 -{r},{r} "
            f"h-{w-2*r} a{r},{r} 0 0 1 -{r},-{r} v-{h-2*r} a{r},{r} 0 0 1 {r},-{r} z")


def circle(cx, cy, r):
    return f"M{cx-r},{cy} a{r},{r} 0 1 0 {2*r},0 a{r},{r} 0 1 0 -{2*r},0 z"


def dpad():
    (cx, cy), a, l = DPAD_C, ARM, LEN
    return (f"M{cx-a},{cy-l} h{2*a} v{l-a} h{l-a} v{2*a} h-{l-a} v{l-a} h-{2*a} v-{l-a} "
            f"h-{l-a} v-{2*a} h{l-a} z")


def m_pixels():
    sx, sy, sw, sh, _ = SCREEN
    gw, gh = len(M[0]) * PX, len(M) * PX
    ox, oy = sx + (sw - gw) / 2, sy + (sh - gh) / 2
    parts = []
    for r, row in enumerate(M):
        for c, ch in enumerate(row):
            if ch == "X":
                x, y = ox + c * PX, oy + r * PX
                parts.append(f"M{x:.2f},{y:.2f} h{PX} v{PX} h-{PX} z")
    return " ".join(parts)


def pills():
    return " ".join(rrect(x, y, w, h, h / 2) for x, y, w, h in PILLS)


def argb(hex_rgb, alpha="FF"):
    return "#" + alpha + hex_rgb[1:]


def gradient(start, end, c1, c2):
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" '
            f'android:startX="{start[0]}" android:startY="{start[1]}" android:endX="{end[0]}" android:endY="{end[1]}" '
            f'android:startColor="{argb(c1)}" android:endColor="{argb(c2)}"/></aapt:attr>')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


bx, by, bw, bh, br = BODY
fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- MicroBoy logo, generated by tools/make_logo.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="{rrect(bx + 1.2, by + 2, bw, bh, br)}" android:fillColor="#40000000"/>
    <path android:pathData="{rrect(*BODY)}">{gradient((bx, by), (bx + bw, by + bh), LAV, CORAL)}</path>
    <path android:pathData="{rrect(*SCREEN)}" android:fillColor="{INK}"/>
    <path android:pathData="{m_pixels()}" android:fillColor="{MINT}"/>
    <path android:pathData="{dpad()}" android:fillColor="{INK}"/>
    <path android:pathData="{circle(*BTN_A, BTN_R)} {circle(*BTN_B, BTN_R)}" android:fillColor="{INK}"/>
    <path android:pathData="{pills()}" android:fillColor="#99{INK[1:]}"/>
</vector>
'''
bg = f'''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0 h108 v108 h-108 z" android:fillColor="{BG}"/>
    <path android:pathData="M0,0 h108 v108 h-108 z">
        <aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="54" android:centerY="50"
            android:gradientRadius="52" android:startColor="#553B2F73" android:endColor="#00{BG[1:]}"/></aapt:attr>
    </path>
</vector>
'''
# Monochrome layer for Android 13 themed icons: body silhouette with screen + controls cut out.
mono = f'''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF"
        android:pathData="{rrect(*BODY)} {rrect(*SCREEN)} {dpad()} {circle(*BTN_A, BTN_R)} {circle(*BTN_B, BTN_R)}"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="{m_pixels()}"/>
</vector>
'''
write(f"{RES}/drawable/ic_launcher_foreground.xml", fg)
write(f"{RES}/drawable/ic_launcher_background.xml", bg)
write(f"{RES}/drawable/ic_launcher_monochrome.xml", mono)
write(f"{RES}/mipmap-anydpi-v26/ic_launcher.xml", '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">
  <defs>
    <linearGradient id="shell" x1="{bx}" y1="{by}" x2="{bx+bw}" y2="{by+bh}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{LAV}"/><stop offset="1" stop-color="{CORAL}"/>
    </linearGradient>
    <radialGradient id="glow" cx="54" cy="50" r="52" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#3B2F73" stop-opacity="0.33"/><stop offset="1" stop-color="{BG}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect x="18" y="18" width="72" height="72" rx="16" fill="{BG}"/>
  <rect x="18" y="18" width="72" height="72" rx="16" fill="url(#glow)"/>
  <path d="{rrect(bx + 1.2, by + 2, bw, bh, br)}" fill="#000" fill-opacity="0.25"/>
  <path d="{rrect(*BODY)}" fill="url(#shell)"/>
  <path d="{rrect(*SCREEN)}" fill="{INK}"/>
  <path d="{m_pixels()}" fill="{MINT}"/>
  <path d="{dpad()}" fill="{INK}"/>
  <path d="{circle(*BTN_A, BTN_R)} {circle(*BTN_B, BTN_R)}" fill="{INK}"/>
  <path d="{pills()}" fill="{INK}" fill-opacity="0.6"/>
</svg>
'''
write("docs/logo.svg", svg)
print("logo written")
