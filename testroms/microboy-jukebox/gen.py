FONT_CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789/"


def tile_bytes(px, tx, ty):
    out = bytearray()
    for y in range(8):
        row = px[ty * 8 + y]
        for x in range(0, 8, 2):
            out.append(row[tx * 8 + x] | (row[tx * 8 + x + 1] << 4))
    return bytes(out)


def build_scene(sc):
    tiles = [bytes(32)]
    index = {tiles[0]: 0}
    maps = []
    for bank, L in enumerate(sc["layers"]):
        if L is None:
            maps.append(None)
            continue
        entries = []
        for block in range(L.w // 256):
            for ty in range(32):
                for tx in range(block * 32, block * 32 + 32):
                    t = tile_bytes(L.px, tx, ty)
                    if t not in index:
                        index[t] = len(tiles)
                        tiles.append(t)
                    i = index[t]
                    entries.append(0 if i == 0 else i | (bank << 12))
        maps.append((entries, L.w // 256))
    assert len(tiles) <= 1024, f"{sc['name']}: {len(tiles)} tiles (max 1024)"

    pal = []
    for L in sc["layers"]:
        cols = (L.colors if L else ["#000000"]) + ["#000000"] * 16
        pal += [bgr555(c) for c in cols[:16]]
    sky = sc["layers"][3]
    pal[0] = 0  # backdrop: black (skies paint every pixel; Data Stream relies on it)

    flash = None
    for f in sc["fx"]:
        if f[0] == "flash":
            L = sc["layers"][f[1]]
            flash = [bgr555(mix(c, "#e8f0ff", 0.6)) for c in (L.colors + ["#000000"] * 16)[:16]]

    sprite_pal = []
    p = sc["particles"]
    ptiles = b""
    if p:
        sp = SpritePalette()
        grids = [[[None if ch == "." else p["legend"][ch] for ch in row] for row in fr] for fr in p["frames"]]
        for g in grids:
            assert len(g) == 8 and all(len(r) == 8 for r in g), sc["name"] + " particle size"
        ptiles = sprite_tiles(grids, 8, sp)
        sprite_pal = sp.colors
    pal += [bgr555(c) for c in (sprite_pal + ["#000000"] * 16)[:16]]

    m = sc["mascot"]
    mtiles = b""
    mascot_pal = []
    if m:
        mp = SpritePalette()
        size = m["size"]
        grids = []
        for fr in m["frames"]:
            g = [[None if ch == "." else m["legend"][ch] for ch in row] for row in fr]
            assert all(len(r) == len(g[0]) for r in g), sc["name"] + " mascot rows"
            grids.append(pad_sprite(g, size) if (len(g) != size or len(g[0]) != size) else g)
        mtiles = sprite_tiles(grids, size, mp)
        mascot_pal = mp.colors
    pal += [bgr555(c) for c in (mascot_pal + ["#000000"] * 16)[:16]]

    music = sc["song"].build()
    return {"tiles": b"".join(tiles), "ntiles": len(tiles), "maps": maps, "pal": pal, "flash": flash,
            "ptiles": ptiles, "mtiles": mtiles, "music": music}


def words(b):
    return [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]


def arr(ctype, name, values, per=12):
    lines = ["    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per)]
    return f"static const {ctype} {name}[{max(1, len(values))}] = {{\n" + ("\n".join(lines) if values else "    0,") + "\n};\n"


def main():
    out = ["// Generated by gen.py. Do not edit.", "#pragma once", "#include <stdint.h>", '#include "scene.h"', ""]
    table = []
    total = 0
    for n, make in enumerate(scenes.ALL):
        sc = make()
        d = build_scene(sc)
        p, m, song = sc["particles"], sc["mascot"], sc["song"]
        tag = f"s{n}"
        out.append(arr("uint32_t", f"{tag}_tiles", words(d["tiles"]), 8))
        mapnames = []
        for i, mp in enumerate(d["maps"]):
            if mp is None:
                mapnames.append(("0", 0))
            else:
                out.append(arr("uint16_t", f"{tag}_map{i}", mp[0], 16))
                mapnames.append((f"{tag}_map{i}", mp[1]))
        out.append(arr("uint16_t", f"{tag}_pal", d["pal"], 16))
        if d["flash"]:
            out.append(arr("uint16_t", f"{tag}_flash", d["flash"], 16))
        if d["ptiles"]:
            out.append(arr("uint32_t", f"{tag}_ptiles", words(d["ptiles"]), 8))
        if d["mtiles"]:
            out.append(arr("uint32_t", f"{tag}_mtiles", words(d["mtiles"]), 8))
        mu = d["music"]
        out.append(arr("uint16_t", f"{tag}_lead", mu["lead"], 16))
        out.append(arr("uint16_t", f"{tag}_harm", mu["harm"], 16))
        out.append(arr("uint16_t", f"{tag}_bass", mu["bass"], 16))
        out.append(arr("uint8_t", f"{tag}_drums", mu["drums"], 32))
        out.append(arr("uint8_t", f"{tag}_wave", mu["wave"], 16))
        fx = [[FX[f[0]], f[1], f[2], f[3], f[4]] for f in sc["fx"]] + [[0] * 5] * 3
        fx = fx[:3]
        name = f"{n + 1:02d}/{len(scenes.ALL)} {sc['name']}"
        fp = lambda v: int(round(v * 256))  # noqa: E731
        members = (m.get("members") if m else None) or [(0, 0)]
        kinds = sum(1 << k for k, (_, kind) in enumerate(members) if kind)
        table.append(
            "    {"
            f" {tag}_tiles, {len(d['tiles']) // 4},"
            f" {{ {', '.join(mn for mn, _ in mapnames)} }}, {{ {', '.join(str(w) for _, w in mapnames)} }},"
            f" {{ {', '.join(str(v) for v in sc['scroll'])} }},"
            f" {tag}_pal, {f'{tag}_flash' if d['flash'] else '0'},"
            f" {{ {', '.join('{' + ', '.join(map(str, f)) + '}' for f in fx)} }},"
            f" {f'{tag}_ptiles' if d['ptiles'] else '0'}, {len(p['frames']) if p else 0}, {p['count'] if p else 0},"
            f" {p['anim'] if p else 0}, {p['sway'] if p else 0}, {fp(p['vx']) if p else 0}, {fp(p['vy']) if p else 0},"
            f" {f'{tag}_mtiles' if d['mtiles'] else '0'}, {len(m['frames']) if m else 0}, {m['size'] if m else 0},"
            f" {MOTION[m['motion']] if m else 0}, {m['anim'] if m else 0}, {m['amp'] if m else 0},"
            f" {m['x'] if m else 0}, {m['y'] if m else 0}, {fp(m['vx']) if m else 0},"
            f" {len(members)}, {kinds}, {{ {', '.join(str(o) for o, _ in members + [(0, 0)] * (8 - len(members)))} }},"
            f" {tag}_lead, {tag}_harm, {tag}_bass, {tag}_drums, {tag}_wave,"
            f" {song.tempo}, {song.swing}, {song.lead[0]}, {song.lead[1]}, {song.lead[2]},"
            f" {song.harm[0]}, {song.harm[1]}, {song.harm[2]}, {song.bass_vol},"
            f' "{name}" }},'
        )
        total += len(d["tiles"])
        print(f"{n + 1:2d} {sc['name']:<18} {d['ntiles']:4d} tiles")
    out.append(f"#define SCENE_COUNT {len(scenes.ALL)}")
    out.append("static const Scene scenes[SCENE_COUNT] = {")
    out += table
    out.append("};\n")
    font = [int(FONT[c][::-1], 2) for c in FONT_CHARS]
    out.append(arr("uint16_t", "fontGlyphs", font))
    out.append(f'static const char fontChars[] = "{FONT_CHARS}";\n')
    with open(os.path.join(HERE, "jukebox.h"), "w") as f:
        f.write("\n".join(out))
    print(f"tile data {total // 1024} KB")


if __name__ == "__main__":
    main()
